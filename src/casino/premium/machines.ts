const lines = (n: number) => ALL_LINES.slice(0, n);
const levels = (lineCount: number, coins: number[]) => coins.map((c) => c * lineCount);
const reg = (a: number, b: number, c: number) => ({ kind: 'regular' as const, pays: [a, b, c] as [number, number, number] });

